import { SCREENS, kmkRef } from "./kmk-2-04-03-19";

export type RequirementDocument = {
  /** «Постановление Президента РУз от … № …» */
  title: string;
  number: string;
  date: string;
  url?: string;
};

/** Реквизиты акта. null — до получения номера и даты от заказчика работ. */
export const DOCUMENT: RequirementDocument | null = null;

/** Ссылка для подписи под расчётом. */
export function requirementRef(): string {
  if (!DOCUMENT) {
    return "отраслевое требование Республики Узбекистан по обязательному применению мембранной очистки (реквизиты документа уточняются)";
  }
  return `${DOCUMENT.title} от ${DOCUMENT.date} № ${DOCUMENT.number}`;
}

