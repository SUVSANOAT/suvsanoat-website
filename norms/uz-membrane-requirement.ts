/* ==================================================================
 * ПРОВЕРКА ПРИГОДНОСТИ СТОКА ДЛЯ МЕМБРАН
 * ================================================================== */

export type MembraneCheckInput = {
  /** жиры на входе в биологию, мг/л */
  fats?: number;
  /** нефтепродукты, мг/л */
  petro?: number;
  /** допустимые жиры перед биологией из коэффициентов расчёта */
  fatsLimit?: number;
};

/**
 * Замечания, которые нужно показать инженеру при обязательном MBR.
 * Не блокируют расчёт: решение остаётся за проектировщиком.
 */
export function membraneWarnings(input: MembraneCheckInput): string[] {
  const out: string[] = [];
  const limit = input.fatsLimit ?? 50;

  if (input.fats !== undefined && input.fats > limit) {
    out.push(
      `Жиры на входе ${Math.round(input.fats)} мг/л при допустимых ${limit} мг/л — ` +
        "перед мембранами обязательна эффективная жироловка и, при необходимости, флотация: " +
        "жиры необратимо забивают поры и сокращают срок службы модулей.",
    );
  }

  if (input.petro !== undefined && input.petro > 5) {
    out.push(
      `Нефтепродукты ${Math.round(input.petro)} мг/л — требуется предварительная очистка до 5 мг/л: ` +
        "органические растворители разрушают полимерные мембраны.",
    );
  }

  out.push(
    `Перед мембранами предусмотрена тонкая решётка ${MBR_FINE_SCREEN.gapMm[0]}–${MBR_FINE_SCREEN.gapMm[1]} мм ` +
      `(${MBR_FINE_SCREEN.source}).`,
  );

  return out;
}

/** Текст для интерфейса и записки, когда требование применено. */
export function requirementNote(applied: boolean): string {
  if (applied) {
    return (
      `Биологическая ступень принята мембранной (MBR): ${requirementRef()}. ` +
      "Мембранные модули заменяют вторичный отстойник — разделение иловой смеси идёт на мембране."
    );
  }
  return (
    `Отступление от требования об обязательной мембранной очистке (${requirementRef()}). ` +
    "Решение принято инженером и должно быть обосновано в проекте."
  );
}
