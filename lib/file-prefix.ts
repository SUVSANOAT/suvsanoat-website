/* ==================================================================
 * ИМЯ ФАЙЛА ПО НАЗВАНИЮ ОРГАНИЗАЦИИ
 *
 * Отдельный файл без единого обращения к базе: то же имя нужно и на
 * сервере, и в браузере — страница сама складывает имя файла, когда
 * собирает документ у себя. Если бы это лежало в lib/brands.ts,
 * страница потянула бы за собой драйвер базы.
 * ================================================================== */

/** Кириллица в латиницу — для имён файлов: их читают файловые системы. */
const TRANSLIT: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z", и: "i",
  й: "y", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t",
  у: "u", ф: "f", х: "h", ц: "c", ч: "ch", ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "",
  э: "e", ю: "yu", я: "ya", "‘": "", "’": "", "«": "", "»": "", "“": "", "”": "",
};

/**
 * Начало имени файла по названию организации: «KOMMUNAL LITI» →
 * «KOMMUNAL_LITI». Остаются только латиница, цифры и подчёркивание:
 * кириллица и апострофы в именах файлов ломаются при пересылке.
 */
export function filePrefix(title: string | null | undefined): string {
  const t = (title ?? "").trim();
  if (!t) return "raschet";
  const latin = [...t.toLowerCase()].map((ch) => TRANSLIT[ch] ?? ch).join("");
  const up = latin.toUpperCase();
  const clean = up.replace(/[^A-Z0-9]+/g, "_").replace(/^_+|_+$/g, "");
  return clean.slice(0, 40) || "raschet";
}

