export type Assumptions = Record<string, number>;

export const DEFAULT_ASSUMPTIONS: Assumptions = Object.fromEntries(
  ASSUMPTIONS.map((a) => [a.key, a.value])
);

export function findAssumption(key: string): AssumptionDef | undefined {
  return ASSUMPTIONS.find((a) => a.key === key);
}

/** значение с проверкой диапазона; вне диапазона — значение по умолчанию */
export function sanitize(key: string, raw: unknown): number | null {
  const def = findAssumption(key);
  if (!def) return null;
  const v = typeof raw === "number" ? raw : parseFloat(String(raw).replace(",", "."));
  if (!Number.isFinite(v) || v < def.min || v > def.max) return null;
  return v;
}

/** объединение значений по умолчанию с переопределениями из базы */
export function mergeAssumptions(overrides: Record<string, unknown> | null | undefined): Assumptions {
  const out: Assumptions = { ...DEFAULT_ASSUMPTIONS };
  if (!overrides) return out;
  for (const [key, raw] of Object.entries(overrides)) {
    const v = sanitize(key, raw);
    if (v !== null) out[key] = v;
  }
  return out;
}
