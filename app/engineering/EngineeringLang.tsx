import { usePathname } from "next/navigation";
import LanguageSwitcher from "../components/LanguageSwitcher";

/** страницы со своей шапкой — там переключатель уже есть */
const OWN_HEADER = ["/engineering"];

export default function EngineeringLang() {
  const pathname = usePathname() ?? "";
  if (OWN_HEADER.includes(pathname)) return null;

  return (
    <div
      className="noPrint"
      style={{
        position: "fixed",
        top: 14,
        right: 16,
        zIndex: 60,
        /* подложка: переключатель лежит поверх таблиц и чертежей,
           и без неё белые буквы теряются на светлых участках */
        background: "rgba(7,20,31,0.82)",
        backdropFilter: "blur(6px)",
        borderRadius: 8,
        padding: 2,
      }}
    >
      <LanguageSwitcher />
    </div>
  );
}
