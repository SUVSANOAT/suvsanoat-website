/* ==================================================================
 * ВИТРИНА РАЗДЕЛА: ЧЕЙ АДРЕС — ТОТ И ЛИСТ
 *
 * На suvsanoat.uz открывается наша витрина: движущаяся сцена, рассказ
 * о том, как рождается проект. Она написана для того, кто ещё не
 * решил. На адресе проектного института она не нужна — там человек
 * уже купил доступ и пришёл считать, и лист должен выглядеть как
 * бланк учреждения.
 *
 * ПОЧЕМУ ВЫБОР ЗДЕСЬ, А НЕ В БРАУЗЕРЕ
 *
 * Сначала я сделал это на стороне браузера: страница спрашивала
 * бренд и подменяла себя. Так делать нельзя. Разметка уже пришла с
 * сервера, и при гидрации старая витрина осталась висеть в документе
 * — на адресе института показывались обе страницы разом. Решение,
 * от которого зависит, ЧТО показать, должно приниматься до отправки
 * разметки, а не после.
 *
 * Чтение домена делает страницу динамической: она собирается на
 * каждый заход, а не отдаётся готовой. Это плата за правильность.
 * Обращение к базе за брендом домена кэшируется на минуту
 * (getBrandByHostCached), поэтому поток посетителей до базы не
 * доходит.
 * ================================================================== */

import { headers } from "next/headers";
import { getBrandByHostCached, type Brand } from "../../lib/brands";
import { dbUrl } from "../../lib/auth";
import EngineeringShowcase from "./EngineeringShowcase";
import BrandLanding from "./BrandLanding";

export default async function EngineeringPage() {
  let brand: Brand | null = null;
  try {
    const host = (await headers()).get("host");
    brand = dbUrl() ? await getBrandByHostCached(host) : null;
  } catch {
    /* Бренд — оформление, а не расчёт: если база недоступна, витрина
       обязана открыться, просто наша. */
    brand = null;
  }

  /* В браузер уходит только оформление. Служебная запись о договоре и
     срок доступа остаются на сервере: всё, что передано странице,
     видно в исходном коде страницы. */
  if (brand) {
    return (
      <BrandLanding
        brand={{
          title: brand.title,
          full_name: brand.full_name,
          logo_url: brand.logo_url,
          accent: brand.accent,
          contact: brand.contact,
        }}
      />
    );
  }
  return <EngineeringShowcase />;
}
