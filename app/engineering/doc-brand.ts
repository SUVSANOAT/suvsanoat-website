"use client";

/* ==================================================================
 * ШАПКА И ТИТУЛ ПЕЧАТНЫХ СТРАНИЦ
 *
 * На страницах расчёта есть печатные бланки: обложка, колонтитул,
 * подпись «расчёт выполнен». В них были вписаны наш логотип, наше
 * имя, наш сайт, телефон и почта. На адресе заказчика это означало,
 * что он печатает документ с чужими контактами — и отдаёт его своему
 * заказчику.
 *
 * Здесь одно место, откуда эти страницы берут данные. Для нашего
 * бренда возвращаются ровно те значения, что были вписаны раньше:
 * печатный бланк на suvsanoat.uz не должен измениться ни на строку.
 * Для чужого — его имя и его логотип, а телефон и почта не
 * подставляются вовсе: чужих контактов у нас нет, и придумывать их
 * нельзя. Пустые строки бланк просто не печатает.
 * ================================================================== */

import { useBrand } from "./BrandHeader";

export type DocBrand = {
  /** имя в шапке; пусто — строка не печатается */
  name: string;
  /** приписка под именем: ENGINEERING SYSTEMS у нас, у других пусто */
  line2: string;
  /** путь к логотипу; пусто — картинка не печатается */
  logo: string;
  /** контактные строки бланка: сайт, телефон, почта */
  contacts: string[];
  /** сайт без протокола; пусто — ссылка не печатается */
  site: string;
  /** телефон; пусто — не печатается */
  phone: string;
  /** почта; пусто — не печатается */
  email: string;
};

const OWN: DocBrand = {
  name: "SUVSANOAT",
  line2: "ENGINEERING SYSTEMS",
  logo: "/suvsanoat-logo.png",
  contacts: ["www.suvsanoat.uz", "+998 77 304 34 00", "suvsanoat@gmail.com"],
  site: "www.suvsanoat.uz",
  phone: "+998 77 304 34 00",
  email: "suvsanoat@gmail.com",
};

/** слаг нашего бренда — см. lib/brands.ts */
const HOME_SLUG = "suvsanoat";

/** пока ответ не пришёл — пусто: мигнуть чужим именем хуже пустоты */
const BLANK: DocBrand = { name: "", line2: "", logo: "", contacts: [], site: "", phone: "", email: "" };

export function useDocBrand(): DocBrand {
  const b = useBrand();
  if (!b) return BLANK;
  if (b.slug === HOME_SLUG) return OWN;
  return {
    name: b.title,
    line2: "",
    logo: b.logo_url,
    /* Единственный контакт, который у нас есть, — строка из записи
       бренда. Телефон и почту не выдумываем. */
    contacts: b.contact ? [b.contact] : [],
    /* Сайта, телефона и почты заказчика у нас нет — и выдумывать их
       нельзя. Бланк печатается без них. */
    site: "",
    phone: "",
    email: "",
  };
}
