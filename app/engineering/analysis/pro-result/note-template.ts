/* ==================================================================
 * ТЕХНИЧЕСКАЯ ЗАПИСКА: ДАННЫЕ ДЛЯ ИИ И ШАБЛОН БЕЗ ИИ
 *
 * NoteInput — всё, что страница результата уже посчитала. Числа
 * приходят отсюда; ни сервер, ни ИИ ничего не пересчитывают и не
 * придумывают. Если ключа API нет или запрос не удался — записка
 * собирается детерминированным шаблоном из тех же данных.
 *
 * Нормативная база — ҚМҚ 2.04.03-19 (реквизиты в KMK_2_04_03_19_DOC);
 * перечень использованных пунктов собирается по ступеням цепочки
 * (kmkClausesFor) и передаётся ИИ полем norms — только на эти пункты
 * ему разрешено ссылаться.
 * ================================================================== */

import { KMK_2_04_03_19_DOC, RELATED_DOCUMENTS, type SzzResult } from "../../../../norms/kmk-2-04-03-19";

export type NotePick = {
  count: number;
  code: string;
  line: string;
  note?: string;
  /** ключевые параметры модели для текста: габариты, объём, DN */
  params: string;
};

export type NoteItem = {
  name: string;
  spec: string;
  qty: string;
  /** own — производит SUVSANOAT, supply — поставка, either — возможны оба */
  supply: "own" | "supply" | "either";
  note?: string;
};

export type NoteStage = {
  index: number;
  key: string;
  title: string;
  what: string;
  makes: "own" | "own-partial" | "supply";
  sizing: string[];
  extra?: string;
  picks: NotePick[];
  /** полный состав оборудования ступени */
  items: NoteItem[];
};

/**
 * Технология биоблока. chosenBy = "engineer" — технология выбрана
 * проектировщиком в форме и рассчитана в calculations/technology.ts;
 * "auto" — автоподбор страницы по расходу и объёмной нагрузке БПК.
 */
export type NoteTechnology = {
  /** код технологии (CAS, MBBR, IFAS, SBR, MBR, UASB, ABR, AnMBR) либо "auto" */
  code: string;
  name: string;
  chosenBy: "engineer" | "auto";
  description: string;
  /** чем нормируется: ҚМҚ 2.04.03-19 либо DWA-A 131 / практика */
  source: string;
  /** расчётный объём биоблока, м³ */
  volumeM3: number;
  /** расход воздуха, Нм³/ч; 0 у анаэробных схем */
  airNm3h: number;
  aerobic: boolean;
  /** допущения расчёта технологии */
  assumptions: string[];
  /** замечания по применимости к составу стока (расчёт не блокируют) */
  warnings: string[];
};

export type NoteInput = {
  industry: string;
  group: string;
  object: string;
  lab: boolean;
  Q: number;
  hours: number;
  Qh: number;
  Qls: number;
  ph: number;
  /** исходный состав: подпись, значение, единица, цель */
  conc: { label: string; value: number; unit: string; target?: number }[];
  special: { label: string; range: [number, number]; unit: string; note: string }[];
  stages: NoteStage[];
  /** общестанционные узлы */
  common: NoteItem[];
  /** исполнение по расходу */
  scale: string;
  /** технология биологического блока: решение инженера либо автоподбор */
  tech?: NoteTechnology;
  /** строительная часть, трубопроводы, площадь, электрика */
  civil?: {
    basins: { name: string; volume: number; L: number; B: number; H: number }[];
    concrete: number;
    rebarT: number;
    formwork: number;
    excavation: number;
    backfill: number;
    note: string;
  };
  pipes?: { name: string; flow: number; dn: number; velocity: number; length: number; material: string }[];
  area?: { structures: number; buildings: number; built: number; site: number; note: string };
  power?: {
    installed: number; demand: number; daily: number; yearly: number;
    specific: number; specificBod: number;
    items: { name: string; qty: number; unit: number; installed: number; hours: number; daily: number; basis: string }[];
    note: string;
  };
  notes: string[];
  sources: string[];
  /** санитарно-защитная зона по табл. 1 ҚМҚ 2.04.03-19; null — по согласованию (прим. 8) */
  szz?: SzzResult | null;
  /** пункты ҚМҚ 2.04.03-19, использованные в расчёте (kmkClausesFor) */
  norms?: string[];
};

