/* ==================================================================
 * ТЕХНИЧЕСКАЯ ЗАПИСКА: ДАННЫЕ ДЛЯ ИИ И ШАБЛОН БЕЗ ИИ
 *
 * NoteInput — всё, что страница результата уже посчитала. Числа
 * приходят отсюда; ни сервер, ни ИИ ничего не пересчитывают и не
 * придумывают. Если ключа API нет или запрос не удался — записка
 * собирается детерминированным шаблоном из тех же данных.
 * ================================================================== */

export type NotePick = {
  count: number;
  code: string;
  line: string;
  note?: string;
  /** ключевые параметры модели для текста: габариты, объём, DN */
  params: string;
};

export type NoteItem = {
  name: string;
  spec: string;
  qty: string;
  /** own — производит SUVSANOAT, supply — поставка, either — возможны оба */
  supply: "own" | "supply" | "either";
  note?: string;
};

export type NoteStage = {
  index: number;
  key: string;
  title: string;
  what: string;
  makes: "own" | "own-partial" | "supply";
  sizing: string[];
  extra?: string;
  picks: NotePick[];
  /** полный состав оборудования ступени */
  items: NoteItem[];
};

export type NoteInput = {
  industry: string;
  group: string;
  object: string;
  lab: boolean;
  Q: number;
  hours: number;
  Qh: number;
  Qls: number;
  ph: number;
  /** исходный состав: подпись, значение, единица, цель */
  conc: { label: string; value: number; unit: string; target?: number }[];
  special: { label: string; range: [number, number]; unit: string; note: string }[];
  stages: NoteStage[];
  /** общестанционные узлы */
  common: NoteItem[];
  /** исполнение по расходу */
  scale: string;
  notes: string[];
  sources: string[];
};

export const NOTE_MAX_STAGES = 16;

function f(v: number, digits = 0): string {
  return v.toLocaleString("ru-RU", { maximumFractionDigits: digits });
}

function today(): string {
  return new Date().toLocaleDateString("ru-RU", { day: "2-digit", month: "long", year: "numeric" });
}

/** проверка структуры тела запроса — от клиента приходит JSON */
export function isNoteInput(x: unknown): x is NoteInput {
  if (!x || typeof x !== "object") return false;
  const o = x as Record<string, unknown>;
  return (
    typeof o.industry === "string" &&
    typeof o.Q === "number" &&
    Array.isArray(o.stages) &&
    (o.stages as unknown[]).length <= NOTE_MAX_STAGES &&
    Array.isArray(o.conc)
  );
}

const MAKES: Record<NoteStage["makes"], string> = {
  own: "изготовление SUVSANOAT (стеклопластик, Ташкент)",
  "own-partial": "корпус и обвязка — SUVSANOAT, технологические узлы — комплектация",
  supply: "комплектация от партнёров",
};

/* ==================================================================
 * ШАБЛОН — используется без ключа API и как страховка
 * ================================================================== */

export function buildTemplateNote(n: NoteInput): string {
  const p: string[] = [];

  p.push(`# Техническая записка. Предварительное решение по очистке сточных вод`);
  p.push(`**Объект:** ${n.object || n.industry}. **Отрасль:** ${n.industry} (${n.group}).`);
  p.push(`**Составлено:** ${today()}, SUVSANOAT, онлайн-расчёт. Стадия — предварительная (П). Не заменяет проектную документацию.`);

  p.push(`## 1. Основание и исходные данные`);
  p.push(
    `Расчётный расход сточных вод Q = ${f(n.Q)} м³/сут при режиме работы ${f(n.hours)} ч/сут, что даёт ${f(n.Qh, 1)} м³/ч (${f(n.Qls, 1)} л/с) в рабочее время. ` +
      (n.lab
        ? `Исходный состав принят по лабораторному анализу заказчика.`
        : `Лабораторный анализ отсутствует; исходный состав принят по справочным данным для отрасли (${n.sources.join("; ")}) в соответствии с практикой КМК 2.04.03-97 для предпроектной стадии. До рабочего проектирования обязателен анализ усреднённой суточной пробы.`)
  );

  p.push(`## 2. Характеристика стока и требования к очистке`);
  const t1 = [`| Показатель | Исходное | Цель | Ед. |`, `|---|---|---|---|`];
  for (const c of n.conc) t1.push(`| ${c.label} | ${f(c.value)} | ${c.target !== undefined ? f(c.target, 1) : "—"} | ${c.unit} |`);
  t1.push(`| pH | ${n.ph.toFixed(1)} | 6,5–8,5 | — |`);
  p.push(t1.join("\n"));
  p.push(`Целевые показатели соответствуют типовым требованиям к сбросу в водный объект рыбохозяйственного значения / городскую сеть; окончательные нормативы принимаются по техническим условиям водоканала или разрешению на сброс.`);
  if (n.special.length) {
    p.push(`Особые загрязнители отрасли, требующие отдельных решений:`);
    p.push(n.special.map((s) => `- **${s.label}** (${s.range[0]}–${s.range[1]} ${s.unit}): ${s.note}`).join("\n"));
  }

  p.push(`## 3. Обоснование технологической схемы`);
  p.push(`Принята ${n.stages.length}-ступенчатая схема. Порядок ступеней следует принципу «от крупного к мелкому, от механики к биологии»: сначала удаляются включения, способные вывести из строя последующие сооружения, затем усредняется поток, затем идёт основная очистка и доведение до норматива.`);
  for (const s of n.stages) {
    p.push(`### ${String(s.index).padStart(2, "0")}. ${s.title}`);
    p.push(`${s.what} Исполнение: ${MAKES[s.makes]}.`);
    p.push([...s.sizing, ...(s.extra ? [s.extra] : [])].map((line) => `- ${line}`).join("\n"));
    if (s.items.length) {
      p.push(`Состав: ` + s.items.map((it) => `${it.name} (${it.qty})`).join("; ") + `.`);
    }
    if (s.picks.length) {
      p.push(
        `Готовое изделие: ` +
          s.picks.map((k) => `${k.count > 1 ? k.count + " × " : ""}**${k.code}** (${k.params})${k.note ? " — " + k.note : ""}`).join("; ") +
          `.`
      );
    }
  }

  p.push(`## 4. Ведомость оборудования`);
  p.push(`Исполнение по расходу: ${n.scale}. Позиции, отмеченные «производим», изготавливает SUVSANOAT; остальное поставляется — на состав решения это не влияет, состав определён технологией.`);
  const supplyWord = (v: NoteItem["supply"]) => (v === "own" ? "производим" : v === "either" ? "производим или поставка" : "поставка");
  const t2 = [`| № | Ступень | Позиция | Расчётный параметр | Кол-во | Исполнение |`, `|---|---|---|---|---|---|`];
  for (const s of n.stages) {
    if (!s.items.length) {
      t2.push(`| ${s.index} | ${s.title} | по индивидуальному расчёту | — | — | — |`);
      continue;
    }
    for (const it of s.items) {
      t2.push(`| ${s.index} | ${s.title} | ${it.name} | ${it.spec} | ${it.qty} | ${supplyWord(it.supply)} |`);
    }
  }
  for (const it of n.common) {
    t2.push(`| — | Общестанционные | ${it.name} | ${it.spec} | ${it.qty} | ${supplyWord(it.supply)} |`);
  }
  p.push(t2.join("\n"));

  const own = n.stages.flatMap((s) => s.picks);
  if (own.length) {
    p.push(
      `Готовые изделия SUVSANOAT, подходящие под позиции ведомости: ` +
        own.map((k) => `${k.count > 1 ? k.count + " × " : ""}**${k.code}** (${k.params})`).join("; ") +
        `.`
    );
  }

  p.push(`## 5. Особенности отрасли, учтённые в решении`);
  p.push(n.notes.map((t) => `- ${t}`).join("\n"));

  p.push(`## 6. Что уточнить на следующей стадии`);
  p.push(
    [
      `- Анализ усреднённой суточной пробы по всем показателям таблицы п. 2, включая температуру и залповые сбросы.`,
      `- Технические условия на сброс (водоканал / экологическая экспертиза) — определяют глубину доочистки и необходимость обеззараживания.`,
      `- Геология площадки и уровень грунтовых вод — для заглублённых корпусов из стеклопластика (расчёт на всплытие, анкеровка).`,
      `- Точки подключения, отметки лотков и располагаемый напор — для гидравлического профиля.`,
      `- Режим работы предприятия по сменам и сезонность — для объёма усреднителя.`,
    ].join("\n")
  );

  p.push(`## 7. Нормативная база`);
  p.push(`КМК 2.04.03-97 «Канализация. Наружные сети и сооружения»; КМК 2.04.01-98; DWA-A 131 (расчёт аэротенков); EN 1825 (жироуловители); EN 858 (сепараторы нефтепродуктов); ${n.sources.join("; ")}.`);

  return p.join("\n\n");
}

