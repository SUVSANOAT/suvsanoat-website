/* ==================================================================
 * КОНТРАКТ СООРУЖЕНИЯ ДЛЯ ГЕНЕРАТОРА ЧЕРТЕЖЕЙ
 *
 * Каждое сооружение библиотеки — параметрическая модель: по числам
 * расчёта (расход, объём, глубина, число секций) она определяет свои
 * габариты и отметки, а затем умеет нарисовать себя на листе (план,
 * разрезы, изометрия). Никаких «рисунков от руки»: за каждый размер
 * отвечает формула, и все размеры — в миллиметрах, отметки — в метрах.
 *
 * Система отметок: относительная, 0.000 — планировочная отметка
 * площадки. Абсолютные отметки подставляются генпланом, если проектировщик
 * задал отметку площадки.
 * ================================================================== */

import type { Dxf } from "./dxf";
import type { Sheet } from "./sheet";

export type Mm = number;
/** отметка, м, относительно 0.000 площадки */
export type Elev = number;

export type StructureKind =
  | "mech" // комплектная механическая очистка (решётка + песколовка-жироловка) на платформе
  | "equal" // усреднитель
  | "mbr" // мембранный биореактор (аноксидная + аэробная + мембранный отсек)
  | "aerotank" // аэротенк коридорный
  | "ring-bio" // кольцевой биореактор с центральным отстойником
  | "clarifier" // вторичный отстойник радиальный
  | "blower" // воздуходувная станция (здание/навес)
  | "thickener" // гравитационный илоуплотнитель
  | "stabilizer" // аэробный стабилизатор
  | "dewatering" // здание обезвоживания осадка
  | "uv" // УФ-обеззараживание + дисковые фильтры (площадка)
  | "contact" // контактный резервуар
  | "sludge-beds" // иловые площадки
  | "pump-station" // КНС
  | "reagent" // реагентное хозяйство
  | "admin" // АБК
  | "transformer"; // ТП

export type Supply = "own" | "supply";

export type Nozzle = {
  /** назначение: вход, выход, ил, воздух, опорожнение */
  role: "in" | "out" | "sludge" | "air" | "drain" | "recirc";
  dn: Mm;
  /** сторона в плане */
  side: "N" | "S" | "E" | "W";
  /** положение вдоль стороны, мм от левого/нижнего угла */
  pos: Mm;
  /** отметка оси патрубка, м */
  elev: Elev;
};

export type VolumeRow = { name: string; m3: number };

/**
 * Шаг расчёта для ведомости на листе.
 *
 * kind: "input" — исходная величина (из анкеты, расчёта расхода, норматива);
 *       "calc"  — вычисленная по формуле;
 *       "check" — проверка условия нормы (результат — «выполняется» / нет).
 */
export type CalcStep = {
  kind: "input" | "calc" | "check";
  /** что определяется: «Рабочий объём аэробной зоны» */
  what: string;
  /** обозначение: «W_аэр» */
  symbol?: string;
  /** формула в общем виде: «W = q · t» (пусто для исходных данных) */
  formula?: string;
  /** подстановка с реальными числами: «W = 148,8 · 6,0» */
  substitution?: string;
  /** результат */
  value: string;
  unit?: string;
  /** основание: пункт норматива, паспорт, практика */
  ref: string;
};
export type EquipmentRow = { name: string; qty: string; spec?: string; supply: Supply };

/** Габаритный контур для компоновки на участке (в плане, мм). */
export type Footprint =
  | { shape: "rect"; w: Mm; l: Mm }
  | { shape: "circle"; d: Mm };

export type StructureModel = {
  id: string;
  kind: StructureKind;
  /** позиция на генплане (01, 02, …) — присваивает сборщик */
  no?: string;
  name: string;
  /** кто изготавливает: стеклопластик SUVSANOAT либо покупное / ж/б подрядчика */
  supply: Supply;
  /** материал корпуса — для штриховки и записки */
  material: "grp" | "concrete" | "steel" | "building";
  footprint: Footprint;
  /** отметки, м: дно, уровень воды, верх (борт) */
  bottom: Elev;
  water: Elev;
  top: Elev;
  /** заглубление: если > 0 — сооружение в земле, планировка на этой отметке */
  ground: Elev;
  nozzles: Nozzle[];
  volumes: VolumeRow[];
  equipment: EquipmentRow[];
  /** расчётные основания — печатаются в примечаниях листа */
  basis: string[];
  /**
   * Ведомость расчёта — печатается таблицей прямо на листе: откуда взяты
   * исходные данные и как из них получен каждый размер. Проектировщик
   * должен иметь возможность проверить чертёж, не открывая ничего больше.
   */
  calc?: CalcStep[];
  /** гидравлика: перепад между входом и выходом, м (потери на сооружении) */
  headLoss: number;
  /** нарисовать сооружение на листе (план + разрезы + изометрия) */
  draw: (sheet: Sheet) => void;
};

/** Единый вход генератора — то, что уже посчитал pro-result. */
export type DrawingInput = {
  object: string;
  industryId: string;
  /** м³/сут */
  q: number;
  hours: number;
  /** максимальный часовой расход, м³/ч */
  qMaxH: number;
  /** концентрации на входе, мг/л */
  bod: number;
  cod: number;
  ss: number;
  fats: number;
  tn: number;
  /** ступени цепочки в порядке потока */
  chain: string[];
  /** технология биологии */
  tech: string;
  /** объёмы из расчёта, м³ */
  vAvg: number;
  vBio: number;
  /** воздух, м³/ч */
  air: number;
  /** осадок, кг СВ/сут */
  dryKg: number;
  /** исполнение по расходу */
  scale: "compact" | "modular" | "concrete";
  /** санитарно-защитная зона, м */
  szz?: number;
  /** участок — см. site/layout.ts */
  site?: SiteInput;
  /** язык листов */
  lang: "ru" | "uz" | "en" | "zh";
};

export type SiteInput = {
  /** контур участка в метрах, обход по часовой стрелке; прямоугольник — 4 точки */
  polygon: [number, number][];
  /** отметка площадки, м абс. (если известна) */
  groundElev?: number;
  /** сторона, с которой подходит коллектор */
  inletSide?: "N" | "S" | "E" | "W";
  /** отметка лотка подводящего коллектора, м абс. */
  inletInvert?: number;
  /** сторона точки сброса */
  outletSide?: "N" | "S" | "E" | "W";
  /** отметка точки сброса, м абс. */
  outletElev?: number;
  /** сторона жилой застройки (для ориентации и СЗЗ) */
  housingSide?: "N" | "S" | "E" | "W";
  /** участок не ограничен — компоновать свободно */
  unlimited?: boolean;
};

export type SheetFile = {
  /** номер листа, напр. SUV-OBJ-C-01003 */
  no: string;
  title: string;
  filename: string;
  dxf: Dxf;
};

/** внутренний хелпер: округление до кратности */
export function roundTo(v: number, step: number): number {
  return Math.ceil(v / step) * step;
}
