/* ==================================================================
 * ВЫПУСК В ВОДОЁМ: РАЗБАВЛЕНИЕ И НЕОБХОДИМАЯ СТЕПЕНЬ ОЧИСТКИ
 *
 * До сих пор программа доводила проект до чертежей и записки, а на
 * согласовании человек оставался один: раздела «условия сброса» не
 * было. Между тем именно он определяет, какую станцию вообще надо
 * строить. Требуемое качество очистки не берётся из головы и не
 * равно ПДК: сточная вода в реке разбавляется, и во сколько раз —
 * это расчёт, а не мнение.
 *
 * КАК СЧИТАЕТСЯ РАЗБАВЛЕНИЕ
 * Метод Фролова — Родзиллера, принятый для рек и водотоков:
 *
 *   n = (q + γ·Q) / q        — кратность разбавления
 *   γ = (1 − e^(−α·∛L)) / (1 + (Q/q)·e^(−α·∛L))
 *   α = ξ·φ·∛(E/q)
 *   E = g·H·v / (37·n_ш·C²)  — коэффициент турбулентной диффузии
 *   C = H^(1/6) / n_ш        — коэффициент Шези
 *
 * Смысл: не вся река участвует в разбавлении сразу. Струя сточной
 * воды смешивается с потоком постепенно, и γ показывает, какая доля
 * расхода реки успела подмешаться к створу на расстоянии L. Отсюда
 * два практических следствия, которые проектировщики упускают:
 *
 *   — Русловой выпуск с рассеивающим оголовком даёт разбавление в
 *     разы больше берегового при том же расходе реки. Это часто
 *     дешевле, чем добавлять ступень очистки.
 *   — Створ считается там, где норма требует, а не там, где удобно.
 *     Для рыбохозяйственного водоёма это обычно сам выпуск.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ ВЫДУМАНО
 * Значения ПДК и фоновых концентраций. ПДК зависят от категории
 * водоёма и берутся из документа, действующего в Узбекистане; фон —
 * из данных наблюдений по конкретной реке. Ни то, ни другое я
 * подставлять не стану: ошибка в одной цифре ПДК меняет технологию
 * станции целиком. Вещества, их ПДК и фон вводит проектировщик, а
 * модуль считает то, что считается — разбавление и требуемое
 * качество на выпуске.
 * ================================================================== */

const G = 9.81;

/** Тип выпуска — определяет коэффициент ξ. */
export const OUTLET_KIND = {
  bank: { xi: 1.0, label: "береговой у уреза воды" },
  channel: { xi: 1.5, label: "русловой сосредоточенный" },
  diffuser: { xi: 1.5, label: "русловой рассеивающий" },
} as const;

export type OutletKind = keyof typeof OUTLET_KIND;

export const DISCHARGE_PRACTICE = {
  roughness: { value: 0.025, note: "коэффициент шероховатости русла 0,025 — равнинная река с песчаным дном; для заросшего или каменистого русла берётся больше, значение из справочника по гидравлике" },
  outletVelocity: { value: [1.0, 2.0] as const, note: "скорость на выходе из оголовка 1–2 м/с: меньше — заиливается, больше — размывает дно и берег" },
  minDilutionForBank: { value: 3, note: "при кратности разбавления ниже 3 береговой выпуск обычно не согласуют: у берега образуется зона, где норма не выполняется" },
  diffuserPorts: { value: [3, 12] as const, note: "число отверстий рассеивающего оголовка 3–12 — практика; шаг принимается не менее 5 диаметров отверстия, иначе струи сливаются и разбавление падает" },
} as const;

export type Substance = {
  name: string;
  /** концентрация в очищенной воде на выходе станции, мг/л */
  effluentMgL: number;
  /** ПДК для водоёма данной категории, мг/л — вводит проектировщик */
  pdkMgL: number;
  /** фоновая концентрация в водоёме выше выпуска, мг/л */
  backgroundMgL: number;
};

export type DischargeInput = {
  /** расход сточных вод, м³/сут */
  flowM3Day: number;
  /** расход водотока расчётной обеспеченности, м³/с (95 % обеспеченности) */
  riverQM3s: number;
  /** средняя глубина водотока, м */
  riverDepthM: number;
  /** средняя скорость течения, м/с */
  riverVelocityMs: number;
  /** расстояние по фарватеру до расчётного створа, м */
  distanceM: number;
  /** коэффициент извилистости: путь по фарватеру / по прямой */
  sinuosity?: number;
  /** шероховатость русла */
  roughness?: number;
  outlet?: OutletKind;
  /** число отверстий рассеивающего оголовка */
  ports?: number;
  substances: Substance[];
  /* Для рыбохозяйственных водоёмов норма часто требует выполнения ПДК
     в самом створе выпуска, без учёта разбавления. Тогда расчёт
     разбавления показателен, но не даёт послабления. */
  noDilutionAllowed?: boolean;
};

export type SubstanceCheck = {
  name: string;
  effluentMgL: number;
  pdkMgL: number;
  backgroundMgL: number;
  /** допустимая концентрация на выпуске с учётом разбавления, мг/л */
  allowedMgL: number;
  ok: boolean;
  /** во сколько раз надо снизить */
  reductionFactor: number;
  comment: string;
};

export type DischargeResult = {
  /** расход стока, м³/с */
  qM3s: number;
  /** коэффициент Шези */
  chezyC: number;
  /** коэффициент турбулентной диффузии, м²/с */
  diffusionE: number;
  /** коэффициент α */
  alpha: number;
  /** доля расхода реки, участвующая в смешении */
  gamma: number;
  /** кратность разбавления */
  dilution: number;
  /** диаметр выпуска, мм */
  outletDnMm: number;
  /** скорость на выходе, м/с */
  outletVelocityMs: number;
  substances: SubstanceCheck[];
  /** требуется ли доочистка */
  needsMore: boolean;
  assumptions: string[];
  warnings: string[];
};

const r2 = (x: number) => Number(x.toFixed(2));
const r3 = (x: number) => Number(x.toFixed(3));

const DN = [100, 150, 200, 250, 300, 350, 400, 500, 600, 700, 800, 900, 1000, 1200, 1400, 1600];

export function calculateDischarge(input: DischargeInput): DischargeResult {
  const warnings: string[] = [];
  const q = input.flowM3Day / 86400; // м³/с
  const Q = Math.max(0.001, input.riverQM3s);
  const H = Math.max(0.1, input.riverDepthM);
  const v = Math.max(0.01, input.riverVelocityMs);
  const L = Math.max(1, input.distanceM);
  const nR = input.roughness ?? DISCHARGE_PRACTICE.roughness.value;
  const phi = Math.max(1, input.sinuosity ?? 1.0);
  const kind = input.outlet ?? "bank";
  const xi = OUTLET_KIND[kind].xi;

  if (q <= 0) {
    warnings.push("Расход сточных вод не задан — расчёт разбавления невозможен.");
  }

  /* --- гидравлика водотока --- */
  const C = Math.pow(H, 1 / 6) / nR;
  const E = (G * H * v) / (37 * nR * C * C);

  /* --- коэффициент смешения --- */
  const alpha = xi * phi * Math.cbrt(E / Math.max(1e-9, q));
  const e = Math.exp(-alpha * Math.cbrt(L));
  const gamma = (1 - e) / (1 + (Q / Math.max(1e-9, q)) * e);
  /* n = (q + γ·Q)/q — коэффициент смешения γ стоит на расходе РЕКИ, а
     не стока: он показывает, какая доля речного расхода успела
     подмешаться к расчётному створу. Поставить γ на q — распространённая
     описка, и она даёт разбавление, равное полному отношению расходов,
     то есть как будто река смешалась мгновенно и целиком. */
  /* РАССЕИВАЮЩИЙ ОГОЛОВОК.
     Он не «умножает разбавление» — он вовлекает в смешение большую
     долю речного расхода, потому что раздаёт сток по ширине потока,
     а не выливает одной струёй. Поэтому множитель ставится на γ, а не
     на кратность, и γ ограничена единицей: больше, чем вся река, в
     смешении участвовать не может. Множитель — корень из числа
     отверстий, а не число: струи частично сливаются, и линейный рост
     был бы приукрашиванием.

     Разница не косметическая. Множитель на кратности легко выводит
     результат за физический предел (q + Q)/q — за то разбавление,
     которое получилось бы, смешайся река мгновенно и целиком. Число,
     которое больше предела, выглядит убедительно и не значит ничего. */
  const ports = kind === "diffuser" ? Math.max(2, Math.round(input.ports ?? 6)) : 1;
  const gammaEff = Math.min(1, gamma * (kind === "diffuser" ? Math.sqrt(ports) : 1));
  const dilution = (q + gammaEff * Q) / Math.max(1e-9, q);

  /* --- оголовок --- */
  const vTarget = 1.5;
  const areaNeeded = q / vTarget;
  const dNeeded = Math.sqrt((4 * areaNeeded) / Math.PI) * 1000;
  const dn = DN.find((d) => d >= dNeeded) ?? DN[DN.length - 1];
  const vActual = q / (Math.PI * Math.pow(dn / 2000, 2));

  /* --- вещества --- */
  const useDilution = !input.noDilutionAllowed;
  const substances: SubstanceCheck[] = input.substances.map((s) => {
    /* C_доп = n·(ПДК − C_ф) + C_ф — стандартная запись условия, при
       котором в расчётном створе концентрация не превысит ПДК. */
    const allowed = useDilution
      ? dilution * (s.pdkMgL - s.backgroundMgL) + s.backgroundMgL
      : s.pdkMgL;
    const ok = s.effluentMgL <= allowed;
    const factor = allowed > 0 ? s.effluentMgL / allowed : Infinity;

    let comment: string;
    if (s.backgroundMgL >= s.pdkMgL) {
      comment =
        `Фон ${s.backgroundMgL} мг/л уже не ниже ПДК ${s.pdkMgL} мг/л. Разбавление здесь не помогает: сколько ни разбавляй, чище фона не станет. ` +
        `Сброс возможен только при концентрации не выше фоновой, и этот вопрос решается с органом согласования, а не расчётом.`;
    } else if (ok) {
      comment = `Проходит: на выпуске ${s.effluentMgL} мг/л при допустимых ${r2(allowed)} мг/л${useDilution ? ` (разбавление ${r2(dilution)})` : " (без учёта разбавления)"}.`;
    } else {
      comment =
        `Не проходит: нужно ${r2(allowed)} мг/л, станция даёт ${s.effluentMgL} мг/л — снизить в ${r2(factor)} раза. ` +
        `Варианты по возрастанию затрат: перенести выпуск в русло с рассеивающим оголовком, увеличить расстояние до расчётного створа, добавить ступень доочистки.`;
    }

    return {
      name: s.name,
      effluentMgL: s.effluentMgL,
      pdkMgL: s.pdkMgL,
      backgroundMgL: s.backgroundMgL,
      allowedMgL: r2(allowed),
      ok,
      reductionFactor: Number.isFinite(factor) ? r2(factor) : 999,
      comment,
    };
  });

  /* --- предупреждения --- */
  if (input.substances.length === 0) {
    warnings.push("Перечень веществ пуст. Расчёт разбавления сам по себе ничего не разрешает: требуемая степень очистки определяется по каждому нормируемому веществу с его ПДК и фоном.");
  }
  if (kind === "bank" && dilution < DISCHARGE_PRACTICE.minDilutionForBank.value) {
    warnings.push(
      `Кратность разбавления ${r2(dilution)} при береговом выпуске. ${DISCHARGE_PRACTICE.minDilutionForBank.note}. Русловой выпуск с рассеивающим оголовком часто дешевле дополнительной ступени очистки — посчитайте оба варианта, прежде чем усложнять станцию.`,
    );
  }
  if (q > Q * 0.5) {
    warnings.push(
      `Расход стока ${r3(q)} м³/с сопоставим с расходом водотока ${Q} м³/с. Это уже не разбавление, а замена воды в реке: метод Фролова — Родзиллера здесь неприменим, требуется расчёт как для водотока со смешанным расходом и согласование в особом порядке.`,
    );
  }
  if (input.noDilutionAllowed) {
    warnings.push("Принято требование выполнения ПДК без учёта разбавления — так нормируется сброс в рыбохозяйственные водоёмы и в черте населённых пунктов. Расчёт разбавления показан для понимания картины, но послабления не даёт.");
  }
  const bad = substances.filter((s) => !s.ok);
  if (bad.length) {
    warnings.push(`Не проходят по требуемому качеству: ${bad.map((s) => s.name).join(", ")}. Пока эти вещества не приведены в норму, проект согласован не будет — это не замечание к оформлению, а условие сброса.`);
  }
  if (vActual < DISCHARGE_PRACTICE.outletVelocity.value[0]) {
    warnings.push(`Скорость на выходе из оголовка ${r2(vActual)} м/с ниже 1 м/с — оголовок будет заиливаться. Уменьшите диаметр или примите оголовок с сужением.`);
  }

  return {
    qM3s: r3(q),
    chezyC: r2(C),
    diffusionE: Number(E.toFixed(5)),
    alpha: r3(alpha),
    gamma: r3(gammaEff),
    dilution: r2(dilution),
    outletDnMm: dn,
    outletVelocityMs: r2(vActual),
    substances,
    needsMore: bad.length > 0,
    assumptions: [
      "Кратность разбавления — метод Фролова — Родзиллера для водотоков; коэффициент турбулентной диффузии по Караушеву.",
      `Выпуск ${OUTLET_KIND[kind].label}, ξ = ${xi}; коэффициент извилистости φ = ${phi}.`,
      `Шероховатость русла ${nR} — ${DISCHARGE_PRACTICE.roughness.note}.`,
      `Расход водотока ${Q} м³/с принят расчётной обеспеченности (обычно 95 % для маловодного месяца); при другой обеспеченности разбавление изменится пропорционально.`,
      ...(kind === "diffuser"
        ? [`Рассеивающий оголовок на ${ports} отверстий: коэффициент смешения увеличен в √${ports} раза и ограничен единицей — оголовок вовлекает в смешение большую долю расхода реки, но не больше, чем всю реку. Точный расчёт ведётся по шагу и скорости истечения отверстий.`]
        : []),
      "ПДК и фоновые концентрации в программу не заложены: они зависят от категории водоёма и данных наблюдений по конкретной реке и вводятся проектировщиком. Ошибка в одной цифре ПДК меняет технологию станции целиком.",
      "Расчёт даёт условия сброса. Оформление НДС и согласование ведутся отдельно и требуют данных гидрологического поста по расчётному водотоку.",
    ],
    warnings,
  };
}
