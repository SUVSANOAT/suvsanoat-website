export type SurfaceShare = {
  /** доля площади водосбора, 0…1 */
  share: number;
  /** коэффициент стока; для кровель и асфальта — null, считается по A */
  z: number | null;
  label: string;
};

export type StormInput = {
  /** интенсивность дождя q20, л/(с·га) — ТОЛЬКО с карты изолиний, рис. 1 */
  q20: number;
  /** климатическая зона по табл. 4 */
  zone?: ClimateZone;
  /** период однократного превышения P, лет — по табл. 5/6 */
  periodYears: number;
  /** площадь водосбора, га */
  areaHa: number;
  /** время поверхностной концентрации t_con, мин (п. 2.16) */
  tConMin?: number;
  /** длина и скорость по лоткам (для t_can) */
  canal?: { lengthM: number; velocity: number };
  /** длина и скорость по трубам (для t_p) */
  pipe?: { lengthM: number; velocity: number };
  /** состав поверхностей водосбора */
  surfaces?: SurfaceShare[];
};

export type StormResult = {
  /** параметр A по ф. (4) */
  A: number;
  n: number;
  mr: number;
  gamma: number;
  /** средний коэффициент стока */
  zMid: number;
  /** составляющие времени, мин */
  tCon: number;
  tCan: number;
  tPipe: number;
  tR: number;
  /** расчётный расход дождевых вод, л/с */
  qLps: number;
  /** он же в м³/ч — для подбора сооружений */
  qM3H: number;
  assumptions: string[];
  warnings: string[];
};

/** ф. (4): A = q20 · 20^n · (1 + lg P / lg m_r)^γ */
export function paramA(q20: number, n: number, mr: number, P: number, gamma: number): number {
  const lgP = Math.log10(Math.max(P, 1e-6));
  const lgMr = Math.log10(Math.max(mr, 1.0001));
  return q20 * Math.pow(20, n) * Math.pow(1 + lgP / lgMr, gamma);
}

/**
 * ф. (6) и (7): время протекания, мин.
 *
 *   t_can = 0,021 · Σ(l_can / v_can),   t_p = 0,017 · Σ(l_p / v_p)
 *
 * Коэффициенты множители, а не делители, и это проверяется физикой:
 * 1/60 переводит секунды в минуты, а остаток — надбавка на неустанови-
 * вшийся режим (0,017 ≈ 1,02/60 для труб, 0,021 ≈ 1,26/60 для лотков,
 * где течение медленнее разгоняется). При делении вместо умножения
 * 600 м при 1,2 м/с дают 8 часов вместо 8 минут — такую ошибку видно
 * сразу, если сверять с секундомером, а не с бумагой.
 */
export function travelTimeMin(lengthM: number, velocity: number, kind: "canal" | "pipe"): number {
  const k = kind === "canal" ? 0.021 : 0.017;
  if (!(lengthM > 0) || !(velocity > 0)) return 0;
  return k * (lengthM / velocity);
}

export function calculateStorm(input: StormInput): StormResult {
  const warnings: string[] = [];
  const zone = input.zone ?? "plains";
  const { n, mr, gammaP1, gammaSub1, label } = TABLE_4[zone];
  const P = Math.max(0.01, input.periodYears);
  const gamma = P >= 1 ? gammaP1 : gammaSub1;

  if (!(input.q20 > 0)) {
    warnings.push(
      "Не задана интенсивность дождя q20. Её берут с карты изолиний (рис. 1 ҚМҚ 2.04.03-19) для площадки объекта; без неё расчёт невозможен, и подставлять «типовое» значение нельзя.",
    );
  }

  const A = paramA(Math.max(0, input.q20), n, mr, P, gamma);

  /* --- средний коэффициент стока --- */
  const surfaces = input.surfaces?.length
    ? input.surfaces
    : [
        { share: 0.6, z: null, label: "кровли и асфальтобетон" },
        { share: 0.4, z: 0.038, label: "газоны, зелёные насаждения" },
      ];
  const sumShare = surfaces.reduce((s, x) => s + Math.max(0, x.share), 0);
  if (Math.abs(sumShare - 1) > 0.02) {
    warnings.push(`Доли поверхностей в сумме дают ${(sumShare * 100).toFixed(0)} %, а должны 100 %. Проверьте состав водосбора.`);
  }
  const zMid = surfaces.reduce((s, x) => s + Math.max(0, x.share) * (x.z ?? zImpervious(A)), 0) / (sumShare || 1);

  /* --- продолжительность, ф. (5)–(7) --- */
  const tCon = input.tConMin ?? 5;
  const tCan = input.canal ? travelTimeMin(input.canal.lengthM, input.canal.velocity, "canal") : 0;
  const tPipe = input.pipe ? travelTimeMin(input.pipe.lengthM, input.pipe.velocity, "pipe") : 0;
  const tR = Math.max(tCon + tCan + tPipe, 1);

  /* --- ф. (2) --- */
  const power = 1.2 * n - 0.1;
  const q = (zMid * Math.pow(A, 1.2) * Math.max(0, input.areaHa)) / Math.pow(tR, power);

  if (tR < 5) {
    warnings.push("Расчётная продолжительность меньше 5 мин: проверьте время поверхностной концентрации (п. 2.16) — при малом t_r расход резко завышается.");
  }

  const assumptions: string[] = [
    `Метод предельных интенсивностей, ${kmkRef("2.11", "ф. (2)")}: q_r = z_mid·A^1,2·F / t_r^(1,2n−0,1).`,
    `Параметр A по ${kmkRef("2.12", "ф. (4)")}: A = q20·20^n·(1 + lgP/lg m_r)^γ = ${A.toFixed(1)} при q20 = ${input.q20} л/(с·га), n = ${n}, m_r = ${mr}, P = ${P} года, γ = ${gamma}.`,
    `Климатические параметры n, m_r, γ — ҚМҚ 2.04.03-19, табл. 4: ${label}.`,
    `Интенсивность q20 = ${input.q20} л/(с·га) принята проектировщиком по карте изолиний (рис. 1); в программе значения q20 не хранятся.`,
    `Период однократного превышения P = ${P} года — по табл. 5 (населённые пункты) или табл. 6 (промышленные предприятия), выбирается по условиям расположения коллектора.`,
    `Средний коэффициент стока z_mid = ${zMid.toFixed(3)}: ${surfaces
      .map((s) => `${s.label} ${(s.share * 100).toFixed(0)} % (z = ${(s.z ?? zImpervious(A)).toFixed(3)})`)
      .join("; ")}. Для кровель и асфальтобетона z зависит от A (табл. 10), для остальных — табл. 9.`,
    `Продолжительность t_r = ${tR.toFixed(1)} мин: поверхностная концентрация ${tCon} мин (${kmkRef("2.16")}), по лоткам ${tCan.toFixed(1)} мин (ф. 6), по трубам ${tPipe.toFixed(1)} мин (ф. 7).`,
    "ВИД ФОРМУЛ (2) И (4) СВЕРИТЬ С ПЕЧАТНЫМ ТЕКСТОМ ҚМҚ 2.04.03-19 перед выпуском рабочей документации: они внесены по машинному чтению норматива, а показатели степени при таком чтении распознаются ненадёжно.",
  ];

  const r2 = (x: number) => Number(x.toFixed(2));
  return {
    A: r2(A),
    n,
    mr,
    gamma,
    zMid: Number(zMid.toFixed(3)),
    tCon: r2(tCon),
    tCan: r2(tCan),
    tPipe: r2(tPipe),
    tR: r2(tR),
    qLps: r2(q),
    qM3H: r2((q * 3600) / 1000),
    assumptions,
    warnings,
  };
}
