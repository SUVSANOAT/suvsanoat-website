/* ==================================================================
 * ДОЖДЕВАЯ (ЛИВНЕВАЯ) КАНАЛИЗАЦИЯ — РАСЧЁТНЫЙ РАСХОД
 *
 * Считается по методу предельных интенсивностей, как он изложен в
 * ҚМҚ 2.04.03-19, раздел 2 (дождевые воды):
 *
 *   q_r = z_mid · A^1,2 · F / t_r^(1,2n − 0,1),  л/с          ф. (2)
 *   A   = q20 · 20^n · (1 + lg P / lg m_r)^γ                  ф. (4)
 *   t_r = t_con + t_can + t_p,  мин                           ф. (5)
 *   t_can = 0,021 · Σ(l_can / v_can)                          ф. (6)
 *   t_p   = 0,017 · Σ(l_p / v_p)                              ф. (7)
 *
 * ВНИМАНИЕ, ЭТО ВАЖНО.
 * Формулы (2) и (4) приведены здесь в том виде, в каком они стоят в
 * этом семействе норм (ҚМҚ 2.04.03-19 воспроизводит методику
 * СНиП 2.04.03-85). Текст ҚМҚ доступен нам только в виде PDF, и
 * распознавание формул в нём ненадёжно: показатели степени и скобки
 * при машинном чтении рассыпаются. Поэтому ПЕРЕД ВЫПУСКОМ РАБОЧЕЙ
 * ДОКУМЕНТАЦИИ проектировщик обязан сверить вид формул (2) и (4) с
 * печатным текстом норматива. Программа об этом говорит прямо, в
 * каждом результате — молчать о таком нельзя.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ ВЫДУМАНО
 * Значение q20 — интенсивность дождя, л/(с·га), при P = 1 год и
 * t = 20 мин — берётся ТОЛЬКО с карты изолиний (рис. 1 норматива) для
 * конкретной площадки. Ни одно число q20 в коде не зашито: карту в
 * виде цифр мы не имеем, а придумывать интенсивность дождя — значит
 * придумывать диаметр коллектора и затопление улицы.
 * ================================================================== */

