/* ==================================================================
 * ОТОПЛЕНИЕ И ВЕНТИЛЯЦИЯ ЗДАНИЙ ОЧИСТНЫХ СООРУЖЕНИЙ
 *
 * Про здания на станции обычно вспоминают последними, и зря: именно
 * они портят пусковой период. Воздуходувная без вытяжки за час
 * нагревается так, что срабатывает тепловая защита двигателей;
 * решётчатое здание без вентиляции — это сероводород над лотком, где
 * стоит оператор; реагентное хозяйство без вытяжки — испарения над
 * баками; неотапливаемое здание с трубопроводами — разморозка в первую
 * же зиму, а в Узбекистане зимой бывает минус пятнадцать.
 *
 * ЧТО СЧИТАЕТСЯ
 * 1. Воздухообмен по кратностям — сколько кубометров в час выкидывать
 *    из каждого помещения, и какой вентилятор под это ставить.
 * 2. Воздухообмен воздуходувной по ТЕПЛОИЗБЫТКАМ, а не по кратности:
 *    там определяет не запах, а киловатты двигателей, ушедшие в тепло.
 *    Кратность в этом помещении — грубая и обычно заниженная оценка.
 * 3. Теплопотери и мощность отопления по удельной характеристике.
 *
 * ГРАНИЦА
 * Кратности воздухообмена и температуры внутреннего воздуха ниже —
 * это требования к зданиям такого назначения, как они сложились в
 * практике проектирования станций; окончательные значения принимаются
 * по ҚМҚ 2.04.05 и по заданию на проектирование, а для помещений с
 * хлором — по правилам безопасности при обращении с хлором, где
 * требования жёстче и включают аварийную вентиляцию с пуском снаружи
 * помещения. ҚМҚ 2.04.03-19 воздухообмен зданий не нормирует.
 * ================================================================== */

export type RoomKind =
  | "screen"      // решётчатое здание
  | "blower"      // воздуходувная
  | "pump"        // насосная станция
  | "reagent"     // реагентное хозяйство
  | "chlorine"    // хлораторная
  | "dewater"     // обезвоживание осадка
  | "lab"         // лаборатория
  | "operator"    // операторная, бытовые
  | "electrical"; // электрощитовая, ТП

