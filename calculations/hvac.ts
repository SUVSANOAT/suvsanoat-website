export type RoomInput = {
  kind: RoomKind;
  /** площадь пола, м² */
  areaM2: number;
  /** высота помещения, м */
  heightM?: number;
  /** установленная мощность двигателей в помещении, кВт (для воздуходувной и щитовой) */
  motorKW?: number;
};

export type RoomResult = {
  label: string;
  volumeM3: number;
  /** приток, м³/ч */
  supplyM3h: number;
  /** вытяжка, м³/ч */
  exhaustM3h: number;
  /** по какому признаку определён воздухообмен */
  basis: string;
  /** подача вентилятора с запасом, м³/ч */
  fanM3h: number;
  tInC: number;
  /** теплопотери, кВт */
  heatLossKW: number;
  /** мощность на нагрев приточного воздуха, кВт */
  heatAirKW: number;
  /** итого на отопление и вентиляцию, кВт */
  heatTotalKW: number;
  note: string;
};

export type HvacResult = {
  rooms: RoomResult[];
  /** суммарная тепловая мощность, кВт */
  heatKW: number;
  /** суммарная вытяжка, м³/ч */
  exhaustM3h: number;
  assumptions: string[];
  warnings: string[];
};

const r1 = (x: number) => Number(x.toFixed(1));

export function calculateHvac(rooms: RoomInput[], tOutC?: number): HvacResult {
  const warnings: string[] = [];
  const tOut = tOutC ?? HVAC_PRACTICE.tOutHeating.value;
  const c = HVAC_PRACTICE.airHeatCap.value;

  const out: RoomResult[] = rooms.map((r) => {
    const spec = ROOMS[r.kind];
    const h = r.heightM ?? (r.kind === "blower" || r.kind === "screen" || r.kind === "dewater" ? 4.2 : 3.0);
    const V = r.areaM2 * h;
    const dT = spec.tIn - tOut;

    let supply = V * spec.supply;
    let exhaust = V * spec.exhaust;
    let basis = `кратность ${spec.supply}/${spec.exhaust} в час`;

    /* --- помещения с тепловыделением: воздухообмен по теплоизбыткам ---
       L = Q / (c · Δt). Здесь Δt — перегрев над НАРУЖНОЙ температурой
       летом, потому что летом воздух и приходит горячим: зимой этот же
       воздухообмен избыточен и его снижают клапаном. */
    if ((r.kind === "blower" || r.kind === "electrical") && r.motorKW && r.motorKW > 0) {
      const heatKW = r.motorKW * HVAC_PRACTICE.motorHeatShare.value;
      const byHeat = (heatKW * 1000) / (c * HVAC_PRACTICE.blowerDeltaT.value);
      supply = byHeat;
      exhaust = byHeat;
      basis = `по теплоизбыткам: ${r1(heatKW)} кВт при перегреве ${HVAC_PRACTICE.blowerDeltaT.value} °C`;
      if (byHeat / V > 20) {
        warnings.push(
          `${spec.label}: воздухообмен по теплоизбыткам ${Math.round(byHeat / V)} крат в час. Для машинного зала это нормально, но естественной вентиляцией столько не проходит: нужны приточный и вытяжной вентиляторы с автоматикой по температуре, а решётки и дефлекторы такой расход не обеспечат. Проверьте, что в стене есть место под приточный проём: ${Math.round(byHeat / 3600 / 2)} м² живого сечения при скорости 2 м/с.`,
        );
      }
    } else if (r.kind === "blower" || r.kind === "electrical") {
      supply = V * 3;
      exhaust = V * 3;
      basis = "мощность оборудования не задана — принята кратность 3; воздухообмен этих помещений определяется теплоизбытками и должен быть пересчитан";
      warnings.push(`${spec.label}: не задана мощность оборудования, воздухообмен принят по кратности. Для этого помещения так считать нельзя — определяющее здесь тепло, а не запах.`);
    }

    const heatLoss = (spec.q0 * V * dT) / 1000;
    /* НАГРЕВ ПРИТОЧНОГО ВОЗДУХА.
       Обычно он больше теплопотерь через стены, и именно его забывают,
       когда подбирают котёл.

       Но в помещении с работающим оборудованием считать его по летнему
       расходу — грубая ошибка в другую сторону: летний воздухообмен там
       задан теплоизбытками, зимой его прикрывают клапаном, а само
       оборудование помещение и отапливает. Насчитать воздуходувной
       тридцать киловатт отопления, когда в ней стоят девять киловатт
       тепловыделений, значит поставить котёл под помещение, которое
       нужно не греть, а остужать. Поэтому здесь зимний воздухообмен
       принимается по санитарной норме, а тепловыделения вычитаются. */
    const motorHeatKW = (r.motorKW ?? 0) * HVAC_PRACTICE.motorHeatShare.value;
    const winterAir = motorHeatKW > 0 ? Math.min(supply, V * 3) : supply;
    const heatAir = Math.max(0, (c * winterAir * dT) / 1000 - motorHeatKW);
    const fan = Math.max(supply, exhaust) * HVAC_PRACTICE.fanReserve.value;

    return {
      label: spec.label,
      volumeM3: Math.round(V),
      supplyM3h: Math.round(supply),
      exhaustM3h: Math.round(exhaust),
      basis,
      fanM3h: Math.round(fan / 50) * 50,
      tInC: spec.tIn,
      heatLossKW: r1(heatLoss),
      heatAirKW: r1(heatAir),
      heatTotalKW: r1(heatLoss + heatAir),
      note: spec.note,
    };
  });

  if (rooms.some((r) => r.kind === "chlorine")) {
    warnings.push(
      "Хлораторная: кратности здесь приведены как ориентир. Помещение с хлором проектируется по правилам безопасности при обращении с хлором — аварийная вентиляция с пуском снаружи, газоанализатор с выводом сигнала, отдельный выход наружу, поглотительная установка. Общестроительными нормами это не закрывается.",
    );
  }
  if (!rooms.some((r) => r.kind === "operator")) {
    warnings.push("В перечне нет операторной. На станции с круглосуточным дежурством помещение для персонала с отоплением и вентиляцией обязательно.");
  }

  return {
    rooms: out,
    heatKW: r1(out.reduce((a, b) => a + b.heatTotalKW, 0)),
    exhaustM3h: Math.round(out.reduce((a, b) => a + b.exhaustM3h, 0)),
    assumptions: [
      `Расчётная температура наружного воздуха ${tOut} °C — ${HVAC_PRACTICE.tOutHeating.note}.`,
      "Кратности воздухообмена и температуры внутреннего воздуха — практика проектирования станций очистки; окончательные принимаются по ҚМҚ 2.04.05 и заданию на проектирование. ҚМҚ 2.04.03-19 воздухообмен зданий не нормирует.",
      "Теплопотери посчитаны по удельной тепловой характеристике здания — это оценка для выбора мощности источника тепла, а не теплотехнический расчёт ограждающих конструкций.",
      `${HVAC_PRACTICE.motorHeatShare.note}.`,
      `${HVAC_PRACTICE.fanReserve.note}. ${HVAC_PRACTICE.standbyFan.note}.`,
      "Мощность на нагрев приточного воздуха показана отдельно от теплопотерь через ограждения: в помещениях с большой кратностью она больше теплопотерь в несколько раз, и котёл, подобранный только по стенам, зимой не справится.",
    ],
    warnings,
  };
}

/** набор помещений по технологической цепочке — чтобы не собирать вручную */
export function roomsFromChain(chain: string[], opts: { blowerKW?: number; areaScale?: number } = {}): RoomInput[] {
  const k = opts.areaScale ?? 1;
  const list: RoomInput[] = [];
  if (chain.includes("screen")) list.push({ kind: "screen", areaM2: 36 * k });
  if (chain.includes("pump") || chain.includes("avg")) list.push({ kind: "pump", areaM2: 30 * k });
  if (chain.includes("bio") || chain.includes("mbr")) list.push({ kind: "blower", areaM2: 40 * k, motorKW: opts.blowerKW });
  if (chain.includes("physchem") || chain.includes("neutral") || chain.includes("daf")) list.push({ kind: "reagent", areaM2: 24 * k });
  if (chain.includes("sludge")) list.push({ kind: "dewater", areaM2: 48 * k });
  list.push({ kind: "electrical", areaM2: 20 * k });
  list.push({ kind: "operator", areaM2: 24 * k });
  return list;
}
