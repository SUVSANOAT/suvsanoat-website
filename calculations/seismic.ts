/* ==================================================================
 * СЕЙСМИКА: ГИДРОДИНАМИКА ВОДЫ В ЁМКОСТИ И ЗАКРЕПЛЕНИЕ ОБОРУДОВАНИЯ
 *
 * Узбекистан — сейсмический район. Ташкент восемь баллов, отдельные
 * районы девять, и это не отвлечённая цифра: в 1966 году город был
 * разрушен толчком, эпицентр которого пришёлся на центр. При этом во
 * всём нашем расчёте слово «сейсмичность» до сих пор стояло только в
 * перечне исходных данных.
 *
 * ЧТО ЗДЕСЬ СЧИТАЕТСЯ И ПОЧЕМУ ЭТО НЕ ПОПРАВОЧНЫЙ КОЭФФИЦИЕНТ
 *
 * Ёмкость с водой при землетрясении ведёт себя не как груз. Вода
 * делится на две части, и они работают по-разному:
 *
 *   ИМПУЛЬСНАЯ часть — нижний слой, который движется вместе со
 *   стенами, как если бы он был к ним приклеен. Она даёт короткий
 *   резкий удар в одной фазе с грунтом.
 *
 *   КОНВЕКТИВНАЯ часть — верхний слой, который качается сам по себе с
 *   периодом в несколько секунд. Она даёт медленную волну, бьющую в
 *   стену и в перекрытие уже после того, как толчок прошёл.
 *
 * Разделение это придумал Хаузнер в пятидесятые, и с тех пор по нему
 * считают все резервуары в мире. Считать вместо этого «вес воды на
 * коэффициент» — значит получить одно неправильное число вместо двух
 * правильных: импульсная часть окажется занижена, а про волну и запас
 * борта не вспомнят вовсе.
 *
 * ТРЕТЬЕ, ЧТО ЛОМАЕТСЯ ПЕРВЫМ
 * Не стены. Первыми рвутся трубопроводы на вводе в сооружение: с одной
 * стороны жёсткая ёмкость на своём основании, с другой — труба в
 * податливом грунте, и при толчке они смещаются по-разному. Поэтому в
 * выводах этого модуля гибкие вставки стоят наравне с арматурой стен,
 * хотя стоят они несопоставимо дешевле.
 *
 * ГРАНИЦА ЧЕСТНОСТИ — ЧИТАТЬ ОБЯЗАТЕЛЬНО
 * Формулы Хаузнера — механика, они одинаковы в любой стране, и здесь
 * они посчитаны полностью. А вот КОЭФФИЦИЕНТЫ, на которые умножается
 * ускорение — категория ответственности, допускаемые повреждения,
 * динамичность, грунтовые условия — берутся из ҚМҚ 2.01.03
 * «Строительство в сейсмических районах». Оцифрованного текста этого
 * документа у нас нет, и выдумывать его значения я не буду. Поэтому
 * сейсмический коэффициент задаётся проектировщиком как ввод, а по
 * умолчанию принято только базовое ускорение по баллам — величина
 * общеизвестная и одинаковая в СНиП II-7-81 и в ҚМҚ. Ниже это
 * повторено в допущениях, чтобы никто не принял результат за расчёт
 * по норме.
 * ================================================================== */

const G = 9.81;

/** Базовое ускорение по баллам — доля g. Значение общеизвестное. */
export const BASE_ACCEL: Record<7 | 8 | 9, number> = { 7: 0.1, 8: 0.2, 9: 0.4 };

/** Грунтовые условия: категория по сейсмическим свойствам. */
export const SOIL_CATEGORY = {
  I: { factor: 0.9, label: "I — скальные и полускальные грунты" },
  II: { factor: 1.0, label: "II — крупнообломочные, песчаные плотные, глинистые твёрдые" },
  III: { factor: 1.3, label: "III — рыхлые пески, мягкопластичные глины, высокий уровень грунтовых вод" },
} as const;

export type SoilCategory = keyof typeof SOIL_CATEGORY;

export const SEISMIC_PRACTICE = {
  anchorSafety: { value: 1.5, note: "коэффициент запаса на анкерное крепление оборудования 1,5 — практика: анкер работает на вырыв в бетоне, разброс прочности заделки велик" },
  frictionCoef: { value: 0.4, note: "коэффициент трения стальной рамы по бетону 0,4 — практика; на удержание оборудования от сдвига одним трением рассчитывать нельзя" },
  flexibleInsertMm: { value: 100, note: "гибкая вставка на вводе трубопровода в сооружение с компенсацией не менее 100 мм в каждом направлении — практика для сейсмических районов" },
  freeboardFactor: { value: 1.0, note: "борт ёмкости должен перекрывать расчётную высоту волны полностью: перелив через стену размывает засыпку у сооружения" },
} as const;

export type SeismicInput = {
  /** расчётная сейсмичность площадки, баллов */
  intensity: 7 | 8 | 9;
  /** категория грунта по сейсмическим свойствам */
  soil?: SoilCategory;
  /** длина ёмкости в направлении толчка, м */
  L: number;
  /** ширина, м */
  B: number;
  /** глубина воды, м */
  hWater: number;
  /** высота стены (борт вместе с водой), м */
  hWall: number;
  /** толщина стены, мм */
  wallMm: number;
  /** масса конструкции, т — если не задана, считается по габаритам */
  structureT?: number;
  /* Сейсмический коэффициент по ҚМҚ 2.01.03: произведение
     коэффициентов ответственности, допускаемых повреждений и
     динамичности. НЕ выдумывается: если не задан, берётся 1,0 и в
     предупреждениях прямо написано, что это не расчёт по норме. */
  kSeismic?: number;
  /* Доля ускорения для КОНВЕКТИВНОЙ части, от базового.
     Волна качается с периодом в несколько секунд, а спектр ускорений
     на таких периодах падает в разы против пикового. Считать волну по
     пиковому ускорению — заметная перестраховка; брать её из спектра
     площадки — правильно, но спектр в программе не зашит. Поэтому
     умолчание 1,0 (в запас), а проектировщик подставляет своё число,
     сняв его со спектра на периоде T, который здесь и посчитан. */
  convectiveFactor?: number;
  /** масса единицы оборудования на закрепление, кг */
  equipmentKg?: number;
  /** высота центра тяжести оборудования над опорой, м */
  equipmentCgM?: number;
  /** база крепления (расстояние между анкерами поперёк опрокидывания), м */
  equipmentBaseM?: number;
};

export type SeismicResult = {
  /** расчётное ускорение, доля g */
  accelG: number;
  /** вся масса воды, т */
  waterT: number;
  /** импульсная масса, т */
  impulsiveT: number;
  /** конвективная масса, т */
  convectiveT: number;
  /** плечо импульсной части от дна, м */
  hImpulsiveM: number;
  /** плечо конвективной части от дна, м */
  hConvectiveM: number;
  /** период колебаний волны, с */
  sloshPeriodS: number;
  /** высота волны у стены, м */
  waveM: number;
  /** свободный борт, м */
  freeboardM: number;
  /** борта хватает */
  freeboardOk: boolean;
  /** горизонтальная сила от воды, кН */
  waterForceKN: number;
  /** горизонтальная сила от конструкции, кН */
  structureForceKN: number;
  /** опрокидывающий момент в заделке стены, кН·м */
  overturningKNm: number;
  /** дополнительный момент на 1 м стены, кН·м/м */
  wallMomentKNmPerM: number;
  /** закрепление оборудования */
  anchors?: {
    shearKN: number;
    upliftKN: number;
    frictionHoldsKN: number;
    needsAnchors: boolean;
    comment: string;
  };
  measures: string[];
  assumptions: string[];
  warnings: string[];
};

const r2 = (x: number) => Number(x.toFixed(2));
const r1 = (x: number) => Number(x.toFixed(1));

export function calculateSeismic(input: SeismicInput): SeismicResult {
  const warnings: string[] = [];
  const soil = input.soil ?? "II";
  const A = BASE_ACCEL[input.intensity];
  const kS = input.kSeismic ?? 1.0;
  const accel = A * SOIL_CATEGORY[soil].factor * kS;

  const { L, B, hWall } = input;
  const h = Math.max(0.1, input.hWater);

  /* ============ РАЗДЕЛЕНИЕ ВОДЫ ПО ХАУЗНЕРУ ============
     Прямоугольная ёмкость, толчок вдоль стороны L.
       m_и/m = th(0,866·L/h) / (0,866·L/h)
       m_к/m = 0,264·(L/h)·th(3,16·h/L)
     Плечи от дна:
       h_и = 0,375·h
       h_к = h·[1 − (ch(3,16h/L) − 1)/((3,16h/L)·sh(3,16h/L))]

     Смысл соотношения L/h простой. Широкая мелкая ёмкость — почти вся
     вода конвективная, она качается; глубокая узкая — почти вся
     импульсная, она бьёт. Аэротенк обычно посередине, и потому в нём
     обе части значимы. */
  const waterT = L * B * h; // м³ = т при плотности 1 т/м³
  const a = 0.866 * (L / h);
  const impRatio = Math.tanh(a) / a;
  const b = 3.16 * (h / L);
  const conRatio = 0.264 * (L / h) * Math.tanh(b);

  const mImp = waterT * impRatio;
  const mCon = waterT * conRatio;
  const hImp = 0.375 * h;
  const hCon = h * (1 - (Math.cosh(b) - 1) / (b * Math.sinh(b)));

  /* Период волны: T = 2π / √( (3,16·g/L)·th(3,16·h/L) ).
     Он получается в несколько секунд, и это важно практически: волна
     приходит в стену уже после того, как основной толчок кончился,
     то есть складывать её с импульсной частью «в лоб» — перестраховка,
     но здесь мы это делаем сознательно, потому что запас на стене
     стоит дёшево, а перелив через борт — дорого. */
  const sloshPeriod = (2 * Math.PI) / Math.sqrt((3.16 * G) / L * Math.tanh(b));

  /* Высота волны у стены — приближённая оценка Хаузнера:
     d ≈ 0,84·(L/2)·(a/g). Это оценка, а не норматив: точная величина
     зависит от спектра площадки. Борт проверяется по ней, и если он
     впритык — надо считать спектром. */
  const cFactor = Math.min(1, Math.max(0.05, input.convectiveFactor ?? 1.0));
  const accelC = accel * cFactor;
  const wave = 0.84 * (L / 2) * accelC;
  const freeboard = Math.max(0, hWall - h);
  const freeboardOk = freeboard >= wave * SEISMIC_PRACTICE.freeboardFactor.value;

  /* ============ СИЛЫ ============ */
  const waterForce = ((mImp * accel + mCon * accelC) * 1000 * G) / 1000; // кН
  const structT =
    input.structureT ??
    (2 * (L + B) * hWall * (input.wallMm / 1000) + L * B * 0.3) * 2.5;
  const structForce = (structT * 1000 * accel * G) / 1000;

  const overturning =
    ((mImp * hImp * accel + mCon * hCon * accelC) * 1000 * G) / 1000 + (structForce * hWall) / 2;

  /* Момент на погонный метр стены, работающей поперёк толчка: сила
     распределяется по двум стенам, перпендикулярным направлению. */
  const wallMoment = (((mImp * hImp * accel + mCon * hCon * accelC) * 1000 * G) / 1000) / (2 * B);

  /* ============ ЗАКРЕПЛЕНИЕ ОБОРУДОВАНИЯ ============ */
  let anchors: SeismicResult["anchors"];
  if (input.equipmentKg && input.equipmentKg > 0) {
    const W = (input.equipmentKg * G) / 1000; // кН
    const shear = W * accel;
    const cg = input.equipmentCgM ?? 0.6;
    const base = Math.max(0.2, input.equipmentBaseM ?? 0.8);
    /* опрокидывание: момент от сдвигающей силы против веса */
    const uplift = Math.max(0, (shear * cg - W * (base / 2)) / base) * SEISMIC_PRACTICE.anchorSafety.value;
    const friction = W * SEISMIC_PRACTICE.frictionCoef.value;
    anchors = {
      shearKN: r2(shear),
      upliftKN: r2(uplift),
      frictionHoldsKN: r2(friction),
      needsAnchors: true,
      comment:
        uplift > 0
          ? `Сдвигающая сила ${r2(shear)} кН, вырывающее усилие на анкер ${r2(uplift)} кН с запасом ${SEISMIC_PRACTICE.anchorSafety.value}. Оборудование при толчке стремится опрокинуться: анкеры работают на вырыв, а не только на срез.`
          : `Сдвигающая сила ${r2(shear)} кН, опрокидывания нет — центр тяжести низкий. Трение даёт ${r2(friction)} кН, но на него полагаться нельзя: при вертикальной составляющей толчка вес на мгновение уменьшается, и трение исчезает вместе с ним. Анкеры ставятся в любом случае.`,
    };
  }

  /* ============ ПРЕДУПРЕЖДЕНИЯ ============ */
  if (input.kSeismic === undefined) {
    warnings.push(
      "Сейсмический коэффициент не задан, принято 1,0. Это НЕ расчёт по ҚМҚ 2.01.03: коэффициенты ответственности, допускаемых повреждений и динамичности берутся из этого документа и здесь не подставлены. Результат показывает физику явления и порядок сил, а не проверку по норме.",
    );
  }
  if (!freeboardOk) {
    warnings.push(
      `Борта не хватает: расчётная волна ${r2(wave)} м, свободный борт ${r2(freeboard)} м. Вода перельётся через стену — это размывает засыпку у сооружения и заливает площадку. Поднимите борт или снизьте рабочий уровень.`,
    );
  }
  if (input.intensity >= 8 && (input.soil ?? "II") === "III") {
    warnings.push(
      "Восемь баллов и более на грунтах III категории (рыхлые пески, высокий УГВ) — сочетание, при котором надо проверять разжижение основания. Ёмкость может не разрушиться и при этом сесть или наклониться, а трубопроводы это не переживут. Вопрос к изысканиям, а не к конструктиву.",
    );
  }
  if (L / h > 8) {
    warnings.push(`Отношение длины к глубине ${r1(L / h)} — ёмкость широкая и мелкая, почти вся вода в ней конвективная. Определяющей будет волна и высота борта, а не давление на стены.`);
  }

  const measures = [
    `Гибкие вставки на всех вводах и выпусках трубопроводов в сооружение — компенсация не менее ${SEISMIC_PRACTICE.flexibleInsertMm.value} мм в каждом направлении. Первыми при толчке рвутся именно эти узлы: ёмкость и труба смещаются по-разному, а стоит вставка на порядок дешевле ремонта.`,
    "Анкерное крепление всего оборудования к фундаментам: воздуходувки, насосы, щиты, ёмкости реагентов. Оборудование «стоит на своём весе» только до первого толчка.",
    "Непрерывное армирование углов и сопряжения стен с днищем: при знакопеременной нагрузке угол работает в обе стороны, и стыковка арматуры внахлёст в углу недопустима.",
    "Технологические трубопроводы не защемлять в стенах наглухо — проходы через стены с гильзами и эластичной заделкой.",
    "Щиты и шкафы КИПиА крепить к полу и к стене, а не только к стене: при толчке шкаф на одном креплении отрывается по верху.",
    ...(input.intensity >= 8
      ? ["При восьми баллах и выше ёмкости с водой рассчитываются как отдельная задача с учётом гидродинамики — этот расчёт даёт исходные силы для неё, но не заменяет её."]
      : []),
  ];

  return {
    accelG: r2(accel),
    waterT: r1(waterT),
    impulsiveT: r1(mImp),
    convectiveT: r1(mCon),
    hImpulsiveM: r2(hImp),
    hConvectiveM: r2(hCon),
    sloshPeriodS: r2(sloshPeriod),
    waveM: r2(wave),
    freeboardM: r2(freeboard),
    freeboardOk,
    waterForceKN: r1(waterForce),
    structureForceKN: r1(structForce),
    overturningKNm: r1(overturning),
    wallMomentKNmPerM: r1(wallMoment),
    anchors,
    measures,
    assumptions: [
      `Расчётная сейсмичность ${input.intensity} баллов, базовое ускорение ${A}·g — величина общеизвестная, совпадает в СНиП II-7-81 и в ҚМҚ 2.01.03.`,
      `Грунт ${SOIL_CATEGORY[soil].label}, коэффициент ${SOIL_CATEGORY[soil].factor}.`,
      `Сейсмический коэффициент ${kS}${input.kSeismic === undefined ? " (не задан, принят 1,0)" : ""} — произведение коэффициентов ответственности, допускаемых повреждений и динамичности по ҚМҚ 2.01.03; в программе не подставляется, задаётся проектировщиком.`,
      "Разделение воды на импульсную и конвективную части — метод Хаузнера для прямоугольного резервуара. Это механика, она не зависит от нормативной базы страны.",
      `Высота волны — приближённая оценка d = 0,84·(L/2)·(a/g). ${SEISMIC_PRACTICE.freeboardFactor.note}.`,
      `Ускорение для конвективной части принято ${cFactor === 1 ? "равным пиковому (доля 1,0)" : `с долей ${cFactor} от пикового`}. Волна качается с периодом ${r2(sloshPeriod)} с, а спектр на таких периодах падает в разы: доля 1,0 — заметный запас, и её стоит уточнить по спектру площадки на этом периоде.`,
      "Импульсная и конвективная составляющие сложены напрямую, хотя приходят они в разное время: период волны в несколько секунд, толчок короче. Это перестраховка, принятая сознательно — запас арматуры в стене дешевле перелива и размыва.",
      "Массы по Хаузнеру — приближение: их сумма отличается от полной массы воды на несколько процентов в обе стороны в зависимости от отношения длины к глубине. На стороне безопасности это не сказывается.",
      `${SEISMIC_PRACTICE.anchorSafety.note}. ${SEISMIC_PRACTICE.frictionCoef.note}.`,
    ],
    warnings,
  };
}
