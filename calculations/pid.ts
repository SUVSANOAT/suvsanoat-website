/* ==================================================================
 * СХЕМА АВТОМАТИЗАЦИИ (P&ID): ПРИБОРЫ, СИГНАЛЫ, БЛОКИРОВКИ
 *
 * Перечень того, что стоит на сооружениях и что приходит в щит. Из
 * него растут три вещи: состав шкафа управления, стоимость КИПиА и
 * техническое задание монтажникам. Пока этого перечня нет, автоматика
 * в проекте существует в виде слова «автоматика» в спецификации.
 *
 * ЧТО ЗДЕСЬ ГЛАВНОЕ
 * Не список приборов — его написать легко. Главное здесь блокировки:
 * что чему запрещает работать. Насос без воды в приёмном резервуаре,
 * воздуходувка без давления в коллекторе, дозатор без потока — это не
 * «неоптимальный режим», это сгоревшее оборудование в первые сутки
 * после пуска. Поэтому у каждой блокировки написано, что она защищает
 * и что произойдёт без неё.
 *
 * ОБОЗНАЧЕНИЯ
 * Позиции приборов — по ГОСТ 21.208: первая буква измеряемая величина
 * (L — уровень, F — расход, P — давление, T — температура, Q — состав
 * или качество, E — электрическая величина), последующие — функция
 * (T — преобразование/передача, S — переключение, A — сигнализация,
 * I — показание, C — регулирование).
 *
 * ҚМҚ 2.04.03-19 состав приборов не нормирует — раздел автоматизации
 * в нём отсутствует. Поэтому весь перечень помечен как практика
 * проектирования, кроме двух мест, где норма всё же говорит по
 * существу: аварийный уровень в приёмном резервуаре (п. 5.18 задаёт
 * его объём) и обязательность резерва воздуходувок (п. 5.29).
 * ================================================================== */

import { kmkRef } from "../norms/kmk-2-04-03-19";

/** тип сигнала в щите */
export type SignalType = "AI" | "AO" | "DI" | "DO";

export type Instrument = {
  /** позиция по ГОСТ 21.208, например «LT-201» */
  tag: string;
  /** где стоит */
  place: string;
  /** что измеряет или чем управляет */
  purpose: string;
  signal: SignalType;
  /** зачем это нужно эксплуатации — простыми словами */
  why: string;
  /** ссылка на норму, если она есть; иначе пометка практики */
  basis: string;
};

export type Interlock = {
  name: string;
  /** условие срабатывания */
  when: string;
  /** что происходит */
  action: string;
  /** что будет, если блокировки нет */
  ifAbsent: string;
};

export type PidResult = {
  instruments: Instrument[];
  interlocks: Interlock[];
  /** число сигналов по типам */
  counts: Record<SignalType, number>;
  /** рекомендация по контроллеру */
  controller: string;
  assumptions: string[];
};

export type PidInput = {
  /** ступени очистки в порядке потока: screen, grit, avg, primary, bio, mbr, post, disinfect, sludge, pump */
  stages: string[];
  /** есть насосная станция на входе */
  inletPump?: boolean;
  /** обеззараживание ультрафиолетом (иначе хлор) */
  uv?: boolean;
  /** число воздуходувок (рабочих) */
  blowers?: number;
  /** реагентное хозяйство */
  dosing?: boolean;
};

const PRACTICE = "практика проектирования; ҚМҚ 2.04.03-19 состав приборов не нормирует";

export function buildPid(input: PidInput): PidResult {
  const has = (s: string) => input.stages.includes(s);
  const I: Instrument[] = [];
  const L: Interlock[] = [];
  let n = 100;
  const tag = (letters: string) => `${letters}-${(n += 1)}`;

  /* ---------------- вход и насосная ---------------- */
  if (input.inletPump || has("pump")) {
    const lt = tag("LT");
    I.push({
      tag: lt,
      place: "Приёмный резервуар КНС",
      purpose: "Уровень сточной воды, непрерывно",
      signal: "AI",
      why: "по нему включаются и выключаются насосы; он же даёт аварийные уровни",
      basis: `объём резервуара — ${kmkRef("5.18")}; сам прибор — ${PRACTICE}`,
    });
    I.push({
      tag: tag("LS"),
      place: "Приёмный резервуар КНС",
      purpose: "Аварийный нижний уровень (сухой ход)",
      signal: "DI",
      why: "отдельный поплавок, не зависящий от основного датчика: при отказе LT насос всё равно остановится",
      basis: PRACTICE,
    });
    I.push({
      tag: tag("LS"),
      place: "Приёмный резервуар КНС",
      purpose: "Аварийный верхний уровень (перелив)",
      signal: "DI",
      why: "сигнал диспетчеру и включение резервного насоса до того, как польётся через край",
      basis: PRACTICE,
    });
    I.push({
      tag: tag("MS"),
      place: "Насосы КНС",
      purpose: "Пуск/останов, состояние и авария каждого насоса",
      signal: "DO",
      why: "чередование рабочего и резервного по наработке, иначе резервный закисает",
      basis: PRACTICE,
    });
    L.push({
      name: "Защита насосов от сухого хода",
      when: `уровень ниже аварийного нижнего (${lt} или поплавок)`,
      action: "останов всех насосов, запрет пуска до восстановления уровня",
      ifAbsent: "рабочее колесо и торцевое уплотнение перегреваются без воды — насос выходит из строя за часы",
    });
  }

  /* ---------------- решётка ---------------- */
  if (has("screen")) {
    I.push({
      tag: tag("LD"),
      place: "Решётка",
      purpose: "Перепад уровней до и после решётки",
      signal: "AI",
      why: "растущий перепад означает забитые прозоры: по нему включается очистка, а не по таймеру",
      basis: PRACTICE,
    });
    I.push({
      tag: tag("MS"),
      place: "Привод решётки и шнековый пресс",
      purpose: "Пуск/останов, авария",
      signal: "DO",
      why: "запуск по перепаду и по расписанию, контроль заклинивания",
      basis: PRACTICE,
    });
    L.push({
      name: "Очистка решётки по перепаду",
      when: "перепад уровней выше заданного",
      action: "пуск граблин, при неснижении перепада — сигнал оператору",
      ifAbsent: "решётка забивается, вода идёт через аварийный обводной канал мимо очистки",
    });
  }

  /* ---------------- расход ---------------- */
  I.push({
    tag: tag("FT"),
    place: "Подводящий коллектор",
    purpose: "Расход на входе, непрерывно",
    signal: "AI",
    why: "учёт поступающего стока: без него нельзя ни считать удельные показатели, ни доказать нагрузку",
    basis: PRACTICE,
  });
  I.push({
    tag: tag("FT"),
    place: "Выпуск очищенной воды",
    purpose: "Расход на выпуске, с накоплением",
    signal: "AI",
    why: "то, что предъявляют контролирующему органу; разница со входом показывает потери и собственные нужды",
    basis: PRACTICE,
  });

  /* ---------------- усреднитель ---------------- */
  if (has("avg")) {
    I.push({
      tag: tag("LT"),
      place: "Усреднитель",
      purpose: "Уровень",
      signal: "AI",
      why: "управление подачей на очистку: усреднитель на то и нужен, чтобы отдавать воду ровно",
      basis: PRACTICE,
    });
    I.push({
      tag: tag("MS"),
      place: "Мешалка усреднителя",
      purpose: "Пуск/останов, авария",
      signal: "DO",
      why: "без перемешивания взвесь ляжет на дно и объём усреднителя уменьшится вдвое за месяцы",
      basis: PRACTICE,
    });
  }

  /* ---------------- биология ---------------- */
  if (has("bio") || has("mbr")) {
    const qt = tag("QT");
    I.push({
      tag: qt,
      place: "Аэротенк, конец аэробной зоны",
      purpose: "Растворённый кислород",
      signal: "AI",
      why: "главный прибор станции: по нему регулируется воздух, а воздух — это половина счёта за электричество",
      basis: PRACTICE,
    });
    I.push({
      tag: tag("QT"),
      place: "Аэротенк",
      purpose: "Концентрация ила (взвешенные вещества)",
      signal: "AI",
      why: "по ней ведут возраст ила и решают, сколько избыточного отводить",
      basis: PRACTICE,
    });
    I.push({
      tag: tag("TT"),
      place: "Аэротенк",
      purpose: "Температура иловой смеси",
      signal: "AI",
      why: `от неё зависит и объём, и воздух: ${kmkRef("6.143", "прим.")} и ${kmkRef("6.156")}`,
      basis: `${kmkRef("6.143", "прим.")}, ${kmkRef("6.156")}`,
    });
    const pt = tag("PT");
    I.push({
      tag: pt,
      place: "Воздушный коллектор",
      purpose: "Давление воздуха",
      signal: "AI",
      why: "рост давления означает забитые диффузоры, падение — прорыв воздуховода",
      basis: PRACTICE,
    });
    const blowers = Math.max(1, input.blowers ?? 2);
    I.push({
      tag: tag("MC"),
      place: `Воздуходувки, ${blowers} рабочих`,
      purpose: "Пуск/останов и задание частоты",
      signal: "AO",
      why: "регулирование по кислороду вместо работы «на полную» — обычно четверть счёта за электричество",
      basis: `резерв воздуходувок — ${kmkRef("5.29")}`,
    });
    L.push({
      name: "Регулирование воздуха по кислороду",
      when: `${qt} ниже или выше заданного диапазона`,
      action: "изменение частоты воздуходувки; при выходе за пределы — сигнал оператору",
      ifAbsent: "воздуходувка работает на полную круглосуточно: перерасход электроэнергии и вспухание ила от переаэрации",
    });
    L.push({
      name: "Защита воздуходувки по давлению",
      when: `${pt} выше предельного`,
      action: "останов воздуходувки и сигнал",
      ifAbsent: "работа на закрытую задвижку или забитые диффузоры перегревает машину и рвёт воздуховод",
    });
    L.push({
      name: "Запрет работы аэротенка без воздуха",
      when: "все воздуходувки остановлены дольше заданного времени",
      action: "аварийный сигнал диспетчеру, автоматический пуск резервной",
      ifAbsent: `ил гибнет за часы, восстановление биоценоза занимает недели (${kmkRef("5.1", "табл. 20")} — первая категория надёжности)`,
    });
  }

  /* ---------------- мембраны ---------------- */
  if (has("mbr")) {
    const dp = tag("PD");
    I.push({
      tag: dp,
      place: "Мембранный блок",
      purpose: "Трансмембранное давление",
      signal: "AI",
      why: "единственный показатель состояния мембран: по нему назначают промывку",
      basis: PRACTICE,
    });
    I.push({
      tag: tag("FT"),
      place: "Пермеат",
      purpose: "Расход фильтрата",
      signal: "AI",
      why: "вместе с давлением даёт проницаемость — по её падению видно зарастание",
      basis: PRACTICE,
    });
    L.push({
      name: "Промывка мембран по давлению",
      when: `${dp} выше заданного`,
      action: "переход на обратную промывку, при неснижении — химическая промывка и сигнал",
      ifAbsent: "мембраны зарастают необратимо; замена комплекта стоит как треть станции",
    });
  }

  /* ---------------- доочистка и обеззараживание ---------------- */
  if (has("post")) {
    I.push({
      tag: tag("PD"),
      place: "Фильтры доочистки",
      purpose: "Перепад давления на фильтре",
      signal: "AI",
      why: "промывка по перепаду, а не по таймеру: иначе моют чистое и не моют грязное",
      basis: PRACTICE,
    });
  }
  if (has("disinfect") || has("post")) {
    if (input.uv) {
      I.push({
        tag: tag("QT"),
        place: "УФ-установка",
        purpose: "Интенсивность излучения ламп",
        signal: "AI",
        why: "лампа светит и после выработки ресурса, но уже не обеззараживает — только датчик это покажет",
        basis: PRACTICE,
      });
      I.push({
        tag: tag("MS"),
        place: "УФ-установка",
        purpose: "Состояние и авария ламп",
        signal: "DI",
        why: "перегоревшая лампа означает сброс необеззараженной воды",
        basis: PRACTICE,
      });
    } else {
      I.push({
        tag: tag("QT"),
        place: "Контактный резервуар, выход",
        purpose: "Остаточный хлор",
        signal: "AI",
        why: `${kmkRef("6.230")} требует остаточного хлора не менее 1,5 мг/л — это и есть доказательство обеззараживания`,
        basis: kmkRef("6.230"),
      });
    }
  }

  /* ---------------- реагенты ---------------- */
  if (input.dosing || has("physchem") || has("neutral")) {
    I.push({
      tag: tag("QT"),
      place: "Камера смешения",
      purpose: "pH",
      signal: "AI",
      why: `биология работает при pH 6,5–8,5 (${kmkRef("6.2")}); дозирование ведут по pH, а не по расходу`,
      basis: kmkRef("6.2"),
    });
    I.push({
      tag: tag("MC"),
      place: "Насосы-дозаторы",
      purpose: "Производительность дозирования",
      signal: "AO",
      why: "доза пропорциональна расходу и корректируется по pH",
      basis: PRACTICE,
    });
    I.push({
      tag: tag("LS"),
      place: "Баки реагентов",
      purpose: "Нижний уровень реагента",
      signal: "DI",
      why: "дозатор, работающий вхолостую, выглядит исправным на щите и не дозирует ничего",
      basis: PRACTICE,
    });
    L.push({
      name: "Запрет дозирования без потока",
      when: "расход на входе ниже минимального",
      action: "останов насосов-дозаторов",
      ifAbsent: "реагент подаётся в стоящую воду — перерасход и локальный проскок концентрации в сооружение",
    });
  }

  /* ---------------- осадок ---------------- */
  if (has("sludge")) {
    I.push({
      tag: tag("LT"),
      place: "Илоуплотнитель",
      purpose: "Уровень осадка",
      signal: "AI",
      why: "по нему включают откачку: переполненный уплотнитель выносит ил обратно в схему",
      basis: PRACTICE,
    });
    I.push({
      tag: tag("MS"),
      place: "Узел обезвоживания",
      purpose: "Пуск/останов, авария",
      signal: "DO",
      why: "работа по смене, блокировка с насосом осадка и станцией флокулянта",
      basis: PRACTICE,
    });
    L.push({
      name: "Согласование узла обезвоживания",
      when: "пуск обезвоживания",
      action: "одновременный пуск насоса осадка и дозатора флокулянта; останов любого из них останавливает узел",
      ifAbsent: "осадок без флокулянта проходит насквозь, а флокулянт без осадка уходит в дренаж",
    });
  }

  /* ---------------- общестанционное ---------------- */
  I.push({
    tag: tag("EI"),
    place: "Вводной щит",
    purpose: "Напряжение, ток, потребляемая мощность",
    signal: "AI",
    why: "учёт электроэнергии по станции и раннее обнаружение перекоса фаз",
    basis: PRACTICE,
  });
  I.push({
    tag: tag("XA"),
    place: "Щит управления",
    purpose: "Общий аварийный сигнал",
    signal: "DO",
    why: "один выход на диспетчерскую или GSM: ночью на станции никого нет",
    basis: PRACTICE,
  });

  const counts: Record<SignalType, number> = { AI: 0, AO: 0, DI: 0, DO: 0 };
  I.forEach((x) => {
    counts[x.signal] += 1;
  });

  /* Резерв 20 % на развитие — практика: доукомплектовать шкаф модулем
     дешевле на стадии проекта, чем переделывать после пуска. */
  const total = counts.AI + counts.AO + counts.DI + counts.DO;
  const controller =
    `Контроллер с запасом 20 % по каждому типу: не менее ${Math.ceil(counts.AI * 1.2)} AI, ` +
    `${Math.ceil(counts.AO * 1.2)} AO, ${Math.ceil(counts.DI * 1.2)} DI, ${Math.ceil(counts.DO * 1.2)} DO ` +
    `(всего ${total} сигналов в расчёте). Панель оператора, журнал событий и связь с диспетчерской.`;

  return {
    instruments: I,
    interlocks: L,
    counts,
    controller,
    assumptions: [
      "Раздела автоматизации в ҚМҚ 2.04.03-19 нет: состав приборов и объём автоматизации — решение проектировщика. Ссылки на нормы приведены там, где норма говорит по существу: температура (п. 6.143, 6.156), остаточный хлор (п. 6.230), pH на входе в биологию (п. 6.2), объём приёмного резервуара (п. 5.18), резерв воздуходувок (п. 5.29), категория надёжности (п. 5.1, табл. 20).",
      "Позиции приборов обозначены по ГОСТ 21.208: первая буква — измеряемая величина, последующие — функция.",
      "Запас 20 % по каналам контроллера — практика: добавить модуль на стадии проекта дешевле, чем переделывать шкаф после пуска.",
      "Аварийные уровни в приёмном резервуаре выполняются отдельными поплавковыми выключателями, независимыми от аналогового датчика: защита не должна зависеть от одного прибора.",
    ],
  };
}
