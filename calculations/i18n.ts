/* ==================================================================
 * ЯЗЫК РАСЧЁТА
 *
 * Половина текста на странице расчёта приходит не из страницы, а из
 * самого движка: предупреждения, допущения, подписи вроде «принят в
 * расчёт». Перевести только подписи полей — значит получить экран,
 * где заголовки узбекские, а объяснения русские. Поэтому язык
 * доводится до движка и до сборщиков документов.
 *
 * Язык — это оформление ответа, а не входная величина расчёта: на
 * числа он не влияет и влиять не может. Поэтому он необязателен и по
 * умолчанию русский: старый вызов без языка работает как работал.
 *
 * Помощник T держит обе формулировки рядом, в одной строке кода.
 * Отдельный словарь с ключами читается хуже: чтобы понять, что
 * увидит человек, пришлось бы ходить в другой файл, и при правке
 * формулировки легко забыть вторую.
 * ================================================================== */

export type Lang = "ru" | "uz";

/** Выбор формулировки по языку. */
export function pick(lang: Lang | undefined, ru: string, uz: string): string {
  return lang === "uz" ? uz : ru;
}

/** Готовый переводчик для одного расчёта: const T = translator(lang). */
export function translator(lang: Lang | undefined): (ru: string, uz: string) => string {
  return (ru, uz) => (lang === "uz" ? uz : ru);
}
